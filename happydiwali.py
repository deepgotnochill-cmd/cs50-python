def show_diya():
    print(" " * 12 + "✨")
    print(" " * 10 + "✨ 🪔 ✨")
    print(" " * 8 + "✨   \\ | /   ✨")
    print(" " * 10 + " \\  |  /")
    print(" " * 12 + "\\ | /")
    print(" " * 13 + "\\|/")
    print(" " * 8 + "________________")
    print(" " * 7 + "/                \\")
    print(" " * 6 + "/__________________\\")


def happy_diwali(name="friend"):
    print("\n" + "🪔 " * 10)
    print(f"\n        HAPPY DIWALI, {name.upper()}!")
    print("  Wishing you light, joy, peace, and lots of sweets!")
    print("\n" + "✨ " * 10 + "\n")
    show_diya()


happy_diwali("everyone")